-- 4. TRIGGERS
-- Snapshot current service price and calculate line total; only checked-in bookings may use services.
CREATE OR REPLACE TRIGGER TRG_SDDV_BIU
BEFORE INSERT OR UPDATE OF MaDatPhong, MaDichVu, SoLuong, DonGiaTaiThoiDiem ON SuDungDichVu
FOR EACH ROW
DECLARE
    v_trangthai DatPhong.TrangThai%TYPE;
    v_dongia DichVu.DonGia%TYPE;
    v_dvtt DichVu.TrangThai%TYPE;
BEGIN
    SELECT TrangThai INTO v_trangthai
      FROM DatPhong WHERE MaDatPhong = :NEW.MaDatPhong;
    IF v_trangthai <> 'DaNhanPhong' THEN
        RAISE_APPLICATION_ERROR(-20021, 'Chi ghi nhan dich vu cho phieu da nhan phong.');
    END IF;

    SELECT DonGia, TrangThai INTO v_dongia, v_dvtt
      FROM DichVu WHERE MaDichVu = :NEW.MaDichVu;
    IF v_dvtt <> 'HoatDong' THEN
        RAISE_APPLICATION_ERROR(-20022, 'Dich vu dang ngung cung cap.');
    END IF;

    IF INSERTING OR :NEW.DonGiaTaiThoiDiem IS NULL THEN
        :NEW.DonGiaTaiThoiDiem := v_dongia;
    END IF;
    :NEW.ThanhTien := ROUND(:NEW.SoLuong * :NEW.DonGiaTaiThoiDiem, 2);
END;
/

-- Prevent invalid date ranges, maintenance rooms and overlapping bookings.
-- COMPOUND TRIGGER: kiểm tra trùng lịch sau khi cả câu lệnh chạy xong
-- (tránh ORA-04091 khi UPDATE DatPhong).
CREATE OR REPLACE TRIGGER TRG_DATPHONG_BIU
FOR INSERT OR UPDATE OF MaPhong, NgayNhanDuKien, NgayTraDuKien, TrangThai ON DatPhong
COMPOUND TRIGGER
    TYPE t_ids IS TABLE OF DatPhong.MaDatPhong%TYPE INDEX BY PLS_INTEGER;
    g_ids t_ids;

    BEFORE EACH ROW IS
        v_phong_tt Phong.TrangThai%TYPE;
    BEGIN
        IF :NEW.NgayTraDuKien <= :NEW.NgayNhanDuKien THEN
            RAISE_APPLICATION_ERROR(-20023, 'Ngay tra phai sau ngay nhan.');
        END IF;

        IF :NEW.TrangThai IN ('DaDat','DaNhanPhong') THEN
            SELECT TrangThai INTO v_phong_tt FROM Phong WHERE MaPhong = :NEW.MaPhong;
            IF v_phong_tt IN ('BaoTri','NgungSuDung') THEN
                RAISE_APPLICATION_ERROR(-20024, 'Phong dang bao tri hoac ngung su dung.');
            END IF;
        END IF;
    END BEFORE EACH ROW;

    AFTER EACH ROW IS
    BEGIN
        IF :NEW.TrangThai IN ('DaDat','DaNhanPhong') THEN
            g_ids(g_ids.COUNT + 1) := :NEW.MaDatPhong;
        END IF;
    END AFTER EACH ROW;

    AFTER STATEMENT IS
        v_count NUMBER;
    BEGIN
        FOR i IN 1 .. g_ids.COUNT LOOP
            SELECT COUNT(*) INTO v_count
              FROM DatPhong n
              JOIN DatPhong d
                ON d.MaPhong = n.MaPhong
               AND d.MaDatPhong <> n.MaDatPhong
               AND d.TrangThai IN ('DaDat','DaNhanPhong')
               AND n.NgayNhanDuKien < d.NgayTraDuKien
               AND n.NgayTraDuKien > d.NgayNhanDuKien
             WHERE n.MaDatPhong = g_ids(i);
            IF v_count > 0 THEN
                RAISE_APPLICATION_ERROR(-20025, 'Phong da duoc dat trong khoang thoi gian nay.');
            END IF;
        END LOOP;
    END AFTER STATEMENT;
END TRG_DATPHONG_BIU;
/

-- 5. REPORTING VIEWS
CREATE OR REPLACE VIEW VW_Phong_ChiTiet AS
SELECT p.MaPhong, p.SoPhong, p.Tang, p.TrangThai AS TrangThaiPhong,
       lp.MaLoaiPhong, lp.TenLoaiPhong, lp.GiaCoBan, lp.SoNguoiToiDa, lp.DienTich
  FROM Phong p JOIN LoaiPhong lp ON lp.MaLoaiPhong = p.MaLoaiPhong;

CREATE OR REPLACE VIEW VW_DatPhong_ChiTiet AS
SELECT dp.MaDatPhong, kh.MaKhachHang, kh.HoTen, kh.SoDienThoai, kh.Email,
       p.MaPhong, p.SoPhong, lp.TenLoaiPhong,
       dp.NgayDat, dp.NgayNhanDuKien, dp.NgayTraDuKien,
       dp.NgayNhanThucTe, dp.NgayTraThucTe, dp.SoNguoi,
       dp.DonGiaPhong, dp.TienCoc, dp.TrangThai,
       nv.HoTen AS NhanVienLap
  FROM DatPhong dp
  JOIN KhachHang kh ON kh.MaKhachHang = dp.MaKhachHang
  JOIN Phong p ON p.MaPhong = dp.MaPhong
  JOIN LoaiPhong lp ON lp.MaLoaiPhong = p.MaLoaiPhong
  LEFT JOIN NhanVien nv ON nv.MaNhanVien = dp.MaNhanVien;

CREATE OR REPLACE VIEW VW_HoaDon_ChiTiet AS
SELECT hd.MaHoaDon, hd.MaDatPhong, kh.HoTen, p.SoPhong,
       hd.NgayLap, hd.TienPhong, hd.TienDichVu, hd.GiamGia,
       hd.TongThanhToan, hd.TienKhachTra, hd.TienThua,
       hd.PhuongThucTT, hd.TrangThaiTT
  FROM HoaDon hd
  JOIN DatPhong dp ON dp.MaDatPhong = hd.MaDatPhong
  JOIN KhachHang kh ON kh.MaKhachHang = dp.MaKhachHang
  JOIN Phong p ON p.MaPhong = dp.MaPhong;

CREATE OR REPLACE VIEW VW_DoanhThu_TheoNgay AS
SELECT TRUNC(NgayLap) AS Ngay,
       COUNT(*) AS SoHoaDon,
       SUM(TongThanhToan) AS DoanhThu
  FROM HoaDon
 WHERE TrangThaiTT = 'DaThanhToan'
 GROUP BY TRUNC(NgayLap);

CREATE OR REPLACE VIEW VW_DoanhThu_TheoLoaiPhong AS
SELECT lp.MaLoaiPhong, lp.TenLoaiPhong,
       COUNT(hd.MaHoaDon) AS SoLuotDat,
       NVL(SUM(hd.TienPhong),0) AS DoanhThuPhong,
       NVL(SUM(hd.TienDichVu),0) AS DoanhThuDichVu,
       NVL(SUM(hd.TongThanhToan),0) AS TongDoanhThu
  FROM HoaDon hd
  JOIN DatPhong dp ON dp.MaDatPhong = hd.MaDatPhong
  JOIN Phong p ON p.MaPhong = dp.MaPhong
  JOIN LoaiPhong lp ON lp.MaLoaiPhong = p.MaLoaiPhong
 WHERE hd.TrangThaiTT = 'DaThanhToan'
 GROUP BY lp.MaLoaiPhong, lp.TenLoaiPhong;

