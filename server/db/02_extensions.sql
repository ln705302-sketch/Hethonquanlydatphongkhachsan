-- Tài khoản online của khách hàng. MatKhauHash NULL = khách tạo tại quầy
ALTER TABLE KhachHang ADD (
    MatKhauHash VARCHAR2(255),
    TrangThai   VARCHAR2(20) DEFAULT 'HoatDong' NOT NULL,
    CONSTRAINT CK_KhachHang_TT CHECK (TrangThai IN ('HoatDong','Khoa'))
);
-- Email (không phân biệt hoa thường) và CCCD không trùng; NULL thì bỏ qua
CREATE UNIQUE INDEX UQ_KhachHang_Email ON KhachHang (LOWER(Email));
CREATE UNIQUE INDEX UQ_KhachHang_CCCD ON KhachHang (CCCD);
CREATE UNIQUE INDEX UQ_NhanVien_Email ON NhanVien (LOWER(Email));

-- Thông tin hiển thị của loại phòng (mảng JSON)
ALTER TABLE LoaiPhong ADD (
    LoaiGiuong VARCHAR2(60),
    TienNghi   VARCHAR2(2000) DEFAULT '[]' NOT NULL,
    HinhAnh    VARCHAR2(4000) DEFAULT '[]' NOT NULL,
    CONSTRAINT CK_LoaiPhong_TienNghi CHECK (TienNghi IS JSON),
    CONSTRAINT CK_LoaiPhong_HinhAnh CHECK (HinhAnh IS JSON)
);

-- Người ở (có thể khác người đặt), mã ưu đãi đã dùng (lưu bản chụp mã),
-- số tiền giảm và phương thức thanh toán dự kiến
ALTER TABLE DatPhong ADD (
    TenKhachO        VARCHAR2(120),
    SDTKhachO        VARCHAR2(20),
    EmailKhachO      VARCHAR2(150),
    MaCodeKM         VARCHAR2(20),
    GiamGia          NUMBER(12,2) DEFAULT 0 NOT NULL,
    PhuongThucDuKien VARCHAR2(20) DEFAULT 'TienMat' NOT NULL,
    CONSTRAINT CK_DatPhong_GiamGia CHECK (GiamGia >= 0),
    CONSTRAINT CK_DatPhong_PTDK CHECK (PhuongThucDuKien IN ('TienMat','ChuyenKhoan','The'))
);
CREATE INDEX IX_DatPhong_MaCodeKM ON DatPhong(MaCodeKM);

ALTER TABLE HoaDon ADD (
    SoDem NUMBER(4) DEFAULT 1 NOT NULL,
    CONSTRAINT CK_HoaDon_SoDem CHECK (SoDem > 0)
);

-- Thông tin khách sạn (chỉ một dòng)
CREATE TABLE KhachSan (
    MaKhachSan   NUMBER(1) DEFAULT 1 NOT NULL,
    TenKhachSan  VARCHAR2(120) NOT NULL,
    ThanhPho     VARCHAR2(120) NOT NULL,
    DiaChi       VARCHAR2(300) NOT NULL,
    SoDienThoai  VARCHAR2(30),
    Email        VARCHAR2(150),
    MoTa         VARCHAR2(2000),
    SoSao        NUMBER(1) DEFAULT 3 NOT NULL,
    HinhAnh      VARCHAR2(4000) DEFAULT '[]' NOT NULL,
    TienIch      VARCHAR2(1000) DEFAULT '[]' NOT NULL,
    CONSTRAINT PK_KhachSan PRIMARY KEY (MaKhachSan),
    CONSTRAINT CK_KhachSan_Mot CHECK (MaKhachSan = 1),
    CONSTRAINT CK_KhachSan_Sao CHECK (SoSao BETWEEN 1 AND 5),
    CONSTRAINT CK_KhachSan_HinhAnh CHECK (HinhAnh IS JSON),
    CONSTRAINT CK_KhachSan_TienIch CHECK (TienIch IS JSON)
);

-- Mã ưu đãi
CREATE TABLE KhuyenMai (
    MaKhuyenMai    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    MaCode         VARCHAR2(20) NOT NULL,
    TieuDe         VARCHAR2(120) NOT NULL,
    MoTa           VARCHAR2(500),
    PhanTramGiam   NUMBER(5,2) DEFAULT 0 NOT NULL,
    SoTienGiam     NUMBER(12,2) DEFAULT 0 NOT NULL,
    SoDemToiThieu  NUMBER(3) DEFAULT 1 NOT NULL,
    ChiDonDauTien  NUMBER(1) DEFAULT 0 NOT NULL,
    TrangThai      VARCHAR2(20) DEFAULT 'HoatDong' NOT NULL,
    CONSTRAINT PK_KhuyenMai PRIMARY KEY (MaKhuyenMai),
    CONSTRAINT UQ_KhuyenMai_Code UNIQUE (MaCode),
    CONSTRAINT CK_KhuyenMai_Giam CHECK (PhanTramGiam BETWEEN 0 AND 100 AND SoTienGiam >= 0
                                        AND (PhanTramGiam > 0 OR SoTienGiam > 0)),
    CONSTRAINT CK_KhuyenMai_Dem CHECK (SoDemToiThieu >= 1),
    CONSTRAINT CK_KhuyenMai_Dau CHECK (ChiDonDauTien IN (0,1)),
    CONSTRAINT CK_KhuyenMai_TT CHECK (TrangThai IN ('HoatDong','Ngung'))
);

-- Mã khách đã lưu (xóa mã thì xóa luôn các lượt lưu)
CREATE TABLE LuuKhuyenMai (
    MaKhachHang  NUMBER NOT NULL,
    MaKhuyenMai  NUMBER NOT NULL,
    NgayLuu      DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_LuuKhuyenMai PRIMARY KEY (MaKhachHang, MaKhuyenMai),
    CONSTRAINT FK_LuuKM_Khach FOREIGN KEY (MaKhachHang) REFERENCES KhachHang(MaKhachHang) ON DELETE CASCADE,
    CONSTRAINT FK_LuuKM_KM FOREIGN KEY (MaKhuyenMai) REFERENCES KhuyenMai(MaKhuyenMai) ON DELETE CASCADE
);

-- Đánh giá: mỗi khách một đánh giá. MaKhachHang NULL = đánh giá mẫu / khách cũ
CREATE TABLE DanhGia (
    MaDanhGia    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    MaKhachHang  NUMBER,
    TenHienThi   VARCHAR2(120) NOT NULL,
    Diem         NUMBER(3,1) NOT NULL,
    NhanXet      VARCHAR2(2000) NOT NULL,
    NgayTao      DATE DEFAULT SYSDATE NOT NULL,
    NgaySua      DATE,
    An           NUMBER(1) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_DanhGia PRIMARY KEY (MaDanhGia),
    CONSTRAINT UQ_DanhGia_Khach UNIQUE (MaKhachHang),
    CONSTRAINT FK_DanhGia_Khach FOREIGN KEY (MaKhachHang) REFERENCES KhachHang(MaKhachHang) ON DELETE SET NULL,
    CONSTRAINT CK_DanhGia_Diem CHECK (Diem BETWEEN 1 AND 10),
    CONSTRAINT CK_DanhGia_An CHECK (An IN (0,1))
);
