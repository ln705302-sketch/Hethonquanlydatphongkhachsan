   Lấy từ SUNRISE_HOTEL_ORACLE23AI.sql của đồ án, giữ nguyên bảng, ràng buộc,
   index và view. Thay đổi duy nhất:

   * TRG_DATPHONG_BIU được viết lại thành COMPOUND TRIGGER.
     Bản gốc là trigger FOR EACH ROW nhưng SELECT chính bảng DatPhong, nên
     mọi lệnh UPDATE DatPhong (nhận phòng, đổi phòng) bị Oracle báo
     ORA-04091 "table is mutating". Bản mới kiểm tra ngày và trạng thái phòng
     ở BEFORE EACH ROW, còn kiểm tra trùng lịch ở AFTER STATEMENT
     (lúc đó bảng không còn "mutating"). Mã lỗi -20023/-20024/-20025 giữ nguyên.

   Phần dữ liệu mẫu nằm trong server/src/seed.js (mật khẩu được băm bcrypt).
