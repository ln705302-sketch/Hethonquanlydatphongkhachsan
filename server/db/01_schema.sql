-- 1. MASTER TABLES
CREATE TABLE KhachHang (
    MaKhachHang       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    HoTen             VARCHAR2(120) NOT NULL,
    NgaySinh          DATE,
    GioiTinh          VARCHAR2(10),
    SoDienThoai       VARCHAR2(20) NOT NULL,
    Email             VARCHAR2(150),
    CCCD              VARCHAR2(20),
    DiaChi            VARCHAR2(300),
    QuocTich          VARCHAR2(60) DEFAULT 'Việt Nam' NOT NULL,
    NgayTao           DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_KhachHang PRIMARY KEY (MaKhachHang),
    CONSTRAINT UQ_KhachHang_SDT UNIQUE (SoDienThoai),
    CONSTRAINT CK_KhachHang_GioiTinh CHECK (GioiTinh IS NULL OR GioiTinh IN ('Nam','Nu','Khac'))
);

CREATE TABLE LoaiPhong (
    MaLoaiPhong       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    TenLoaiPhong      VARCHAR2(60) NOT NULL,
    MoTa              VARCHAR2(1000),
    GiaCoBan          NUMBER(12,2) NOT NULL,
    SoNguoiToiDa      NUMBER(3) DEFAULT 2 NOT NULL,
    DienTich          NUMBER(8,2),
    TrangThai         VARCHAR2(20) DEFAULT 'HoatDong' NOT NULL,
    CONSTRAINT PK_LoaiPhong PRIMARY KEY (MaLoaiPhong),
    CONSTRAINT UQ_LoaiPhong_Ten UNIQUE (TenLoaiPhong),
    CONSTRAINT CK_LoaiPhong_Gia CHECK (GiaCoBan >= 0),
    CONSTRAINT CK_LoaiPhong_SoNguoi CHECK (SoNguoiToiDa > 0),
    CONSTRAINT CK_LoaiPhong_TT CHECK (TrangThai IN ('HoatDong','Ngung'))
);

CREATE TABLE Phong (
    MaPhong           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    MaLoaiPhong       NUMBER NOT NULL,
    SoPhong           VARCHAR2(15) NOT NULL,
    Tang              NUMBER(3),
    MoTa              VARCHAR2(500),
    TrangThai         VARCHAR2(20) DEFAULT 'Trong' NOT NULL,
    CONSTRAINT PK_Phong PRIMARY KEY (MaPhong),
    CONSTRAINT UQ_Phong_So UNIQUE (SoPhong),
    CONSTRAINT FK_Phong_Loai FOREIGN KEY (MaLoaiPhong) REFERENCES LoaiPhong(MaLoaiPhong),
    CONSTRAINT CK_Phong_TT CHECK (TrangThai IN ('Trong','DangO','BaoTri','NgungSuDung'))
);

CREATE TABLE DichVu (
    MaDichVu          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    TenDichVu         VARCHAR2(120) NOT NULL,
    MoTa              VARCHAR2(500),
    DonGia            NUMBER(12,2) NOT NULL,
    DonViTinh         VARCHAR2(30) DEFAULT 'Lan' NOT NULL,
    TrangThai         VARCHAR2(20) DEFAULT 'HoatDong' NOT NULL,
    CONSTRAINT PK_DichVu PRIMARY KEY (MaDichVu),
    CONSTRAINT UQ_DichVu_Ten UNIQUE (TenDichVu),
    CONSTRAINT CK_DichVu_Gia CHECK (DonGia >= 0),
    CONSTRAINT CK_DichVu_TT CHECK (TrangThai IN ('HoatDong','Ngung'))
);

CREATE TABLE NhanVien (
    MaNhanVien        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    HoTen             VARCHAR2(120) NOT NULL,
    TenDangNhap       VARCHAR2(60) NOT NULL,
    MatKhauHash       VARCHAR2(255) NOT NULL,
    Email             VARCHAR2(150),
    SoDienThoai       VARCHAR2(20),
    VaiTro            VARCHAR2(20) DEFAULT 'LeTan' NOT NULL,
    TrangThai         VARCHAR2(20) DEFAULT 'HoatDong' NOT NULL,
    NgayTao           DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_NhanVien PRIMARY KEY (MaNhanVien),
    CONSTRAINT UQ_NhanVien_User UNIQUE (TenDangNhap),
    CONSTRAINT CK_NhanVien_VaiTro CHECK (VaiTro IN ('QuanLy','LeTan')),
    CONSTRAINT CK_NhanVien_TT CHECK (TrangThai IN ('HoatDong','Khoa'))
);

-- 2. TRANSACTION TABLES
CREATE TABLE DatPhong (
    MaDatPhong        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    MaKhachHang       NUMBER NOT NULL,
    MaPhong           NUMBER NOT NULL,
    MaNhanVien        NUMBER,
    NgayDat           DATE DEFAULT SYSDATE NOT NULL,
    NgayNhanDuKien    DATE NOT NULL,
    NgayTraDuKien     DATE NOT NULL,
    NgayNhanThucTe    DATE,
    NgayTraThucTe     DATE,
    SoNguoi           NUMBER(3) DEFAULT 1 NOT NULL,
    DonGiaPhong       NUMBER(12,2) NOT NULL,
    TienCoc           NUMBER(12,2) DEFAULT 0 NOT NULL,
    GhiChu            VARCHAR2(1000),
    TrangThai         VARCHAR2(20) DEFAULT 'DaDat' NOT NULL,
    CONSTRAINT PK_DatPhong PRIMARY KEY (MaDatPhong),
    CONSTRAINT FK_DatPhong_Khach FOREIGN KEY (MaKhachHang) REFERENCES KhachHang(MaKhachHang),
    CONSTRAINT FK_DatPhong_Phong FOREIGN KEY (MaPhong) REFERENCES Phong(MaPhong),
    CONSTRAINT FK_DatPhong_NV FOREIGN KEY (MaNhanVien) REFERENCES NhanVien(MaNhanVien),
    CONSTRAINT CK_DatPhong_Ngay CHECK (NgayTraDuKien > NgayNhanDuKien),
    CONSTRAINT CK_DatPhong_SoNguoi CHECK (SoNguoi > 0),
    CONSTRAINT CK_DatPhong_Tien CHECK (DonGiaPhong >= 0 AND TienCoc >= 0),
    CONSTRAINT CK_DatPhong_TT CHECK (TrangThai IN ('DaDat','DaNhanPhong','DaTraPhong','DaHuy'))
);

CREATE TABLE SuDungDichVu (
    MaSuDung          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    MaDatPhong        NUMBER NOT NULL,
    MaDichVu          NUMBER NOT NULL,
    NgaySuDung        DATE DEFAULT SYSDATE NOT NULL,
    SoLuong           NUMBER(10,2) DEFAULT 1 NOT NULL,
    DonGiaTaiThoiDiem NUMBER(12,2) NOT NULL,
    ThanhTien         NUMBER(12,2) NOT NULL,
    GhiChu            VARCHAR2(500),
    CONSTRAINT PK_SuDungDichVu PRIMARY KEY (MaSuDung),
    CONSTRAINT FK_SDDV_DatPhong FOREIGN KEY (MaDatPhong) REFERENCES DatPhong(MaDatPhong),
    CONSTRAINT FK_SDDV_DichVu FOREIGN KEY (MaDichVu) REFERENCES DichVu(MaDichVu),
    CONSTRAINT CK_SDDV_SoLuong CHECK (SoLuong > 0),
    CONSTRAINT CK_SDDV_Tien CHECK (DonGiaTaiThoiDiem >= 0 AND ThanhTien >= 0)
);

CREATE TABLE HoaDon (
    MaHoaDon          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    MaDatPhong        NUMBER NOT NULL,
    MaNhanVien        NUMBER,
    NgayLap           DATE DEFAULT SYSDATE NOT NULL,
    TienPhong         NUMBER(12,2) NOT NULL,
    TienDichVu        NUMBER(12,2) DEFAULT 0 NOT NULL,
    GiamGia           NUMBER(12,2) DEFAULT 0 NOT NULL,
    TongThanhToan     NUMBER(12,2) NOT NULL,
    TienKhachTra      NUMBER(12,2) DEFAULT 0 NOT NULL,
    TienThua          NUMBER(12,2) DEFAULT 0 NOT NULL,
    PhuongThucTT      VARCHAR2(20) DEFAULT 'TienMat' NOT NULL,
    TrangThaiTT       VARCHAR2(20) DEFAULT 'ChuaThanhToan' NOT NULL,
    GhiChu            VARCHAR2(500),
    CONSTRAINT PK_HoaDon PRIMARY KEY (MaHoaDon),
    CONSTRAINT UQ_HoaDon_DatPhong UNIQUE (MaDatPhong),
    CONSTRAINT FK_HoaDon_DatPhong FOREIGN KEY (MaDatPhong) REFERENCES DatPhong(MaDatPhong),
    CONSTRAINT FK_HoaDon_NV FOREIGN KEY (MaNhanVien) REFERENCES NhanVien(MaNhanVien),
    CONSTRAINT CK_HoaDon_Tien CHECK (TienPhong >= 0 AND TienDichVu >= 0 AND GiamGia >= 0 AND TongThanhToan >= 0 AND TienKhachTra >= 0 AND TienThua >= 0),
    CONSTRAINT CK_HoaDon_PTTT CHECK (PhuongThucTT IN ('TienMat','ChuyenKhoan','The')),
    CONSTRAINT CK_HoaDon_TT CHECK (TrangThaiTT IN ('ChuaThanhToan','DaThanhToan','HoanTien'))
